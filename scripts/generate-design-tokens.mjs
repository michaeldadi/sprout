import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(
  fs.readFileSync(path.join(root, "design/tokens.json"), "utf8"),
);
const check = process.argv.includes("--check");
let dirty = false;
function write(name, value) {
  const filename = path.join(root, name);
  if (fs.existsSync(filename) && fs.readFileSync(filename, "utf8") === value)
    return;
  if (check) {
    console.error(`Outdated design tokens: ${name}`);
    dirty = true;
    return;
  }
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  fs.writeFileSync(filename, value);
}
for (const role of Object.keys(tokens.colors.light)) {
  const contents = {
    colors: ["light", "dark"].map((mode) => {
      const hex = tokens.colors[mode][role];
      return {
        ...(mode === "dark"
          ? { appearances: [{ appearance: "luminosity", value: "dark" }] }
          : {}),
        color: {
          "color-space": "srgb",
          components: {
            alpha: "1.000",
            red: `0x${hex.slice(0, 2)}`,
            green: `0x${hex.slice(2, 4)}`,
            blue: `0x${hex.slice(4, 6)}`,
          },
        },
        idiom: "universal",
      };
    }),
    info: { author: "xcode", version: 1 },
  };
  write(
    `apps/ios/Sprout/Resources/Assets.xcassets/Sprout${role[0].toUpperCase() + role.slice(1)}.colorset/Contents.json`,
    JSON.stringify(contents, null, 2) + "\n",
  );
}
write(
  "apps/ios/Sprout/Shared/Design/GeneratedDesignTokens.swift",
  `// Generated by scripts/generate-design-tokens.mjs.\nimport Foundation\n\nenum SproutDesignTokens {\n    static let spacing: [CGFloat] = [${tokens.spacing.join(", ")}]\n${Object.entries(
    tokens.corners,
  )
    .map(([k, v]) => `    static let ${k}Corner: CGFloat = ${v}`)
    .join("\n")}\n${Object.entries(tokens.motion)
    .map(([k, v]) => `    static let ${k}: Double = ${v / 1000}`)
    .join("\n")}\n}\n`,
);
write(
  "apps/android/app/src/main/java/com/michaeldadi/sprout/ui/theme/GeneratedDesignTokens.kt",
  `// Generated by scripts/generate-design-tokens.mjs.\npackage com.michaeldadi.sprout.ui.theme\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n${[
    "light",
    "dark",
  ]
    .map(
      (mode) =>
        `internal val Generated${mode[0].toUpperCase() + mode.slice(1)}Colors = SproutColors(\n${Object.entries(
          tokens.colors[mode],
        )
          .map(([k, v]) => `    ${k} = Color(0xFF${v})`)
          .join(",\n")}\n)`,
    )
    .join("\n\n")}\n\nobject SproutDimensions {\n${Object.entries(
    tokens.corners,
  )
    .map(([k, v]) => `    val ${k}Corner = ${v}.dp`)
    .join("\n")}\n}\n`,
);
if (dirty) process.exitCode = 1;
